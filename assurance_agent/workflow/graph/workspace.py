# 逻辑路径解析


def _resolutions(roots: Mapping[str, str], rel: str) -> list[tuple[str, str]]:
    """物理相对路径 → 所有可能的 ``(逻辑 root, root 内路径)``（root 可能互为别名）。"""
    found: list[tuple[str, str]] = []
    for name, prefix in roots.items():
        if prefix == ".":
            found.append((name, rel))
        elif rel.startswith(f"{prefix}/"):
            found.append((name, rel[len(prefix) + 1 :]))
    return found


def _canonical_logical(roots: Mapping[str, str], rel: str) -> str:
    """确定性 canonical 逻辑路径：最长前缀优先，并列按 root 名字典序。"""
    found = _resolutions(roots, rel)
    if not found:
        raise WorkspaceError(f"path resolves outside every logical root: {rel}")
    name, logical = min(found, key=lambda item: (-len(roots[item[0]]), item[0]))
    return f"{name}:{logical}"


def _is_authorized(roots: Mapping[str, str], rel: str, claims: ResourceClaims) -> bool:
    for name, logical in _resolutions(roots, rel):
        claim = ResourcePath.parse(f"{name}:{logical}")
        if any(path_covers(authorization, claim) for authorization in claims.authorization_writes):
            return True
    return False


def _physical_for(roots: Mapping[str, str], logical: ResourcePath) -> str:
    prefix = roots.get(logical.root)
    if prefix is None:
        raise WorkspaceError(f"unknown logical root: {logical.root}")
    prefix = _assert_safe_prefix(prefix)
    return logical.pattern if prefix == "." else f"{prefix}/{logical.pattern}"


