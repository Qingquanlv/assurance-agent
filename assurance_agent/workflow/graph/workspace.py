"""task 私有写层与内容寻址 write-set（Plan → Execute → Update 的 Execute/Update 底座）。

每个 write-capable task 在同一 committed snapshot 的私有物化副本中执行；handler
只持有 ``TaskWorkspace`` 内的路径。task 完成后，coordinator 独立计算 before/after
diff，逐条对照 ``authorization_writes`` fail closed，把新 blob 与 write-set manifest
写入 change dir 下的内容寻址对象库（``.graph-runtime/objects/sha256/<前两位>/<digest>``），
``write_set_id`` 即 manifest 规范字节的 sha256。Update 按 structural task ID 排序合并
write-sets，校验 sibling 不重叠、entry before 与 base tree 一致、canonical root 无漂移，
再以 temp-file + ``os.replace`` 幂等物化到 canonical root；partial apply 重放必收敛。

tree manifest 是按路径排序的规范 JSON，记录 ``kind``/``sha256``/executable mode 与逻辑
root 映射（``change:``/``project:``/``repo:`` → 树内前缀）。capture 排除 ``.git/``、
``.graph-runtime/``、``.worktrees/``、``.venv/``、``.opencode/``、``eval/``、
``benchmark/``、``node_modules/``、``__pycache__/``、``.pytest_cache/``、``.ruff_cache/``、
``.hypothesis/``、``htmlcov/``，
以及 change-dir coordinator 文件
（``events.jsonl``、``workflow-state.yaml``、``running-tasks.json``、
``.progression.lock``、``driver.json``、``driver.lock``）与执行期副作用文件
（``.coverage``、``db.sqlite3``[+shm/wal]）；变化的 symlink 与解析到逻辑 root 之外的路径
一律拒绝。对象库由 coordinator 独占写入，不暴露给 handler。
"""

