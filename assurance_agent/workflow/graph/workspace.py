# TaskWorkspace 与后端


@dataclass(frozen=True)
class TaskWorkspace:
    task_id: str
    root: Path
    project_root: Path
    repo_root: Path
    change_dir: Path
    base_tree_id: str

    def cleanup(self) -> None:
        shutil.rmtree(self.root, ignore_errors=True)

    @classmethod
    def from_materialized_root(cls, task_id: str, root: Path, base_tree_id: str) -> "TaskWorkspace":
        """从物化 root 的 tree manifest 解析逻辑 project/repo/change root。

        manifest 缺失、root 未声明、root 目录不存在或解析到物化 root 之外，
        一律拒绝。
        """
        manifest_path = root / _TREE_MANIFEST_RELPATH
        try:
            payload = json.loads(manifest_path.read_bytes())
        except (OSError, json.JSONDecodeError) as exc:
            raise WorkspaceError(f"materialized root lacks a tree manifest: {root}") from exc
        raw_roots = payload.get("roots") if isinstance(payload, dict) else None
        if not isinstance(raw_roots, dict):
            raise WorkspaceError(f"materialized tree manifest lacks roots: {root}")
        resolved_root = root.resolve()

        def resolve_logical(name: str) -> Path:
            prefix = raw_roots.get(name)
            if not isinstance(prefix, str):
                raise WorkspaceError(f"tree manifest missing logical root '{name}': {root}")
            candidate = (resolved_root / _assert_safe_prefix(prefix)).resolve()
            if not _is_within(candidate, resolved_root):
                raise WorkspaceError(f"logical root '{name}' escapes materialized root: {root}")
            if not candidate.is_dir():
                raise WorkspaceError(f"logical root '{name}' missing in materialized root: {root}")
            return candidate

        return cls(
            task_id=task_id,
            root=root,
            project_root=resolve_logical("project"),
            repo_root=resolve_logical("repo"),
            change_dir=resolve_logical("change"),
            base_tree_id=base_tree_id,
        )


def _assert_safe_task_id(task_id: str) -> None:
    if not task_id or task_id in (".", "..") or "/" in task_id or "\\" in task_id:
        raise WorkspaceError(f"unsafe task_id for workspace directory: {task_id!r}")


class WorkspaceBackend:
    def __init__(self, change_dir: Path) -> None:
        self._tasks_root = change_dir / _TASKS_RELPATH

    def create(
        self,
        *,
        task_id: str,
        base_tree_id: str,
        store: TreeStore,
        side_effect_free: bool = False,
    ) -> TaskWorkspace:
        _assert_safe_task_id(task_id)
        root = self._tasks_root / task_id
        if root.exists():
            shutil.rmtree(root)
        root.mkdir(parents=True)
        store.materialize(base_tree_id, root)
        self._init_convenience_git(root, side_effect_free=side_effect_free)
        return TaskWorkspace.from_materialized_root(task_id, root, base_tree_id)

    @staticmethod
    def _init_convenience_git(root: Path, *, side_effect_free: bool) -> None:
        """task 本地 git 便利索引：给 phase agent ``git status``/``git diff`` 基线。

        不共享 canonical 仓库元数据。git 不存在时跳过；初始化失败对 agent
        target 是 contract error，仅显式 side-effect-free 的 builtin target
        可以忽略。
        """
        git = shutil.which("git")
        if git is None:
            return
        try:
            subprocess.run(
                [git, "init", "-q"], cwd=root, check=True, capture_output=True, timeout=_GIT_TIMEOUT_S
            )
            subprocess.run(
                [git, "add", "-f", "-A"],
                cwd=root,
                check=True,
                capture_output=True,
                timeout=_GIT_TIMEOUT_S,
            )
        except (OSError, subprocess.SubprocessError) as exc:
            if side_effect_free:
                return
            raise WorkspaceError(f"task-local git convenience index failed: {exc}") from exc


