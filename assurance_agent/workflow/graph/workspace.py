# TreeStore：内容寻址对象库 + tree capture/materialize + write-set freeze/merge


class TreeStore:
    """change dir 下的内容寻址对象库；coordinator 独占写入。"""

    def __init__(self, change_dir: Path) -> None:
        self._change_dir = change_dir
        self._objects = change_dir / _OBJECTS_RELPATH

    # ---- 对象库原语 ----

    def _object_path(self, digest: str) -> Path:
        _assert_digest(digest)
        return self._objects / digest[:2] / digest

    def _write_object(self, digest: str, data: bytes) -> None:
        path = self._object_path(digest)
        path.parent.mkdir(parents=True, exist_ok=True)
        try:
            with open(path, "xb") as handle:
                handle.write(data)
                handle.flush()
                os.fsync(handle.fileno())
        except FileExistsError:
            # 已存在的对象必须先验证 hash 再复用：篡改/冲突不允许静默通过。
            self._read_object(digest)

    def _read_object(self, digest: str) -> bytes:
        path = self._object_path(digest)
        try:
            data = path.read_bytes()
        except OSError as exc:
            raise WorkspaceError(f"object missing from store: {digest}") from exc
        if hashlib.sha256(data).hexdigest() != digest:
            raise WorkspaceError(f"object store bytes tampered: {digest}")
        return data

    # ---- tree capture / materialize ----

    def _roots(self, project_root: Path, repo_root: Path | None) -> dict[str, str]:
        def prefix(path: Path) -> str:
            resolved = path.resolve()
            if resolved == project_root:
                return "."
            try:
                return resolved.relative_to(project_root).as_posix()
            except ValueError as exc:
                raise WorkspaceError(f"logical root escapes project root: {path}") from exc

        return {
            "change": prefix(self._change_dir),
            "project": ".",
            "repo": prefix(repo_root) if repo_root is not None else ".",
        }

    def capture(self, project_root: Path, *, repo_root: Path | None = None) -> str:
        """把 project root 固化成内容寻址 tree manifest，返回 tree id（确定性）。"""
        project_root = project_root.resolve()
        if not project_root.is_dir():
            raise WorkspaceError(f"project root is not a directory: {project_root}")
        roots = self._roots(project_root, repo_root)
        entries = _walk(project_root, keep_change_dir=self._change_dir)
        for rel, entry in entries.items():
            if entry.kind == "file":
                data = (project_root / rel).read_bytes()
                if hashlib.sha256(data).hexdigest() != entry.sha256:
                    raise WorkspaceError(f"path changed during capture: {rel}")
            else:
                data = os.readlink(project_root / rel).encode("utf-8")
            self._write_object(entry.sha256, data)
        raw = _canonical_json(_tree_payload(roots, entries))
        tree_id = hashlib.sha256(raw).hexdigest()
        self._write_object(tree_id, raw)
        return tree_id

    def _load_tree(self, tree_id: str) -> _TreeManifest:
        return _parse_tree(self._read_object(tree_id))

    def read_json(self, tree_id: str, logical_path: str) -> ResolvedArtifact:
        """Read a JSON artifact from a committed tree by logical path (change:/project:/repo:)."""
        logical = ResourcePath.parse(logical_path)
        manifest = self._load_tree(tree_id)
        rel = _physical_for(manifest.roots, logical)
        entry = manifest.entries.get(rel)
        if entry is None or entry.kind != "file":
            raise FileNotFoundError(logical_path)
        data = self._read_object(entry.sha256)
        try:
            value = json.loads(data.decode("utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError) as exc:
            raise ValueError(f"artifact is not valid JSON: {logical_path}") from exc
        return ResolvedArtifact(value=value, reads_sha256={logical_path: entry.sha256})

    def materialize(self, tree_id: str, dest: Path) -> None:
        """把 tree 物化到空目录 ``dest``，并写入 ``.graph-runtime/tree.json`` 元数据。"""
        manifest = self._load_tree(tree_id)
        dest = dest.resolve()
        dest.mkdir(parents=True, exist_ok=True)
        for prefix in manifest.roots.values():
            (dest / prefix).mkdir(parents=True, exist_ok=True)
        for rel, entry in sorted(manifest.entries.items()):
            target = (dest / rel).resolve()
            if not _is_within(target, dest):
                raise WorkspaceError(f"tree entry escapes materialization root: {rel}")
            data = self._read_object(entry.sha256)
            if entry.kind == "symlink":
                link_target = data.decode("utf-8")
                if not _is_within((target.parent / link_target).resolve(), dest):
                    raise WorkspaceError(f"tree symlink escapes materialization root: {rel}")
                target.parent.mkdir(parents=True, exist_ok=True)
                os.symlink(link_target, target)
            else:
                _install_file(target, data, entry.executable)
        manifest_path = dest / _TREE_MANIFEST_RELPATH
        manifest_path.parent.mkdir(parents=True, exist_ok=True)
        manifest_path.write_bytes(manifest.raw)

    # ---- write-set freeze / load ----

    def freeze_write_set(
        self,
        workspace: "TaskWorkspace",
        *,
        claims: ResourceClaims,
        outputs: tuple[str, ...] = (),
    ) -> WriteSet:
        """独立计算 workspace 与 base tree 的完整 diff，校验授权与 outputs 后固化。

        每个实际变化路径必须被 ``authorization_writes`` 覆盖（fail closed）；
        变化的 symlink 一律拒绝；声明的 output 必须是存在的具体文件。
        """
        base = self._load_tree(workspace.base_tree_id)
        current = _walk(workspace.root)
        entries: list[WriteEntry] = []
        for rel in sorted(set(base.entries) | set(current)):
            if _is_excluded_rel(rel):
                # Runtime side-effects may still sit in older base trees; never
                # promote them into write-sets once they are capture-excluded.
                continue
            before = base.entries.get(rel)
            after = current.get(rel)
            if before == after:
                continue
            if (before is not None and before.kind == "symlink") or (
                after is not None and after.kind == "symlink"
            ):
                raise WorkspaceError(f"changed symlink rejected: {rel}")
            logical = _canonical_logical(base.roots, rel)
            if not _is_authorized(base.roots, rel, claims):
                raise WorkspaceError(f"forbidden write outside authorization_writes: {logical}")
            if after is None:
                entries.append(
                    WriteEntry(
                        logical_path=logical,
                        operation="delete",
                        before_sha256=before.sha256 if before else None,
                        after_sha256=None,
                        blob_sha256=None,
                    )
                )
                continue
            data = (workspace.root / rel).read_bytes()
            if hashlib.sha256(data).hexdigest() != after.sha256:
                raise WorkspaceError(f"path changed during freeze: {rel}")
            self._write_object(after.sha256, data)
            entries.append(
                WriteEntry(
                    logical_path=logical,
                    operation="add" if before is None else "modify",
                    before_sha256=before.sha256 if before else None,
                    after_sha256=after.sha256,
                    blob_sha256=after.sha256,
                    executable=after.executable,
                )
            )
        outputs_sha256 = self._freeze_outputs(base.roots, current, outputs, workspace=workspace)
        payload: dict[str, object] = {
            "base_tree_id": workspace.base_tree_id,
            "entries": [entry.model_dump(mode="json") for entry in entries],
            "kind": "write_set",
            "outputs_sha256": outputs_sha256,
            "task_id": workspace.task_id,
            "version": 1,
        }
        raw = _canonical_json(payload)
        write_set_id = hashlib.sha256(raw).hexdigest()
        self._write_object(write_set_id, raw)
        return WriteSet(
            write_set_id=write_set_id,
            task_id=workspace.task_id,
            base_tree_id=workspace.base_tree_id,
            entries=tuple(entries),
            outputs_sha256=outputs_sha256,
        )

    def _freeze_outputs(
        self,
        roots: Mapping[str, str],
        current: Mapping[str, _Entry],
        outputs: tuple[str, ...],
        *,
        workspace: "TaskWorkspace | None" = None,
    ) -> dict[str, str]:
        frozen: dict[str, str] = {}
        for declared in outputs:
            logical = ResourcePath.parse(declared)
            if logical.root == "global" or any("*" in segment for segment in logical.segments):
                raise WorkspaceError(f"declared output must be a concrete file path: {declared}")
            rel = _physical_for(roots, logical)
            entry = current.get(rel)
            if entry is not None and entry.kind == "file":
                frozen[declared] = entry.sha256
                continue
            # Directory outputs (schema trailing slash, e.g. change:cases/) — require
            # at least one captured file under the prefix and hash the closure.
            dir_declared = declared.rstrip().endswith("/")
            prefix = f"{rel}/"
            under = {
                path: item
                for path, item in current.items()
                if path.startswith(prefix) and item.kind == "file"
            }
            if dir_declared or under:
                if not under:
                    raise WorkspaceError(f"declared output directory empty or missing: {declared}")
                canonical = "\n".join(f"{path}:{item.sha256}" for path, item in sorted(under.items()))
                frozen[declared] = hashlib.sha256(canonical.encode()).hexdigest()
                continue
            # coordinator projection files are excluded from tree walk but may be
            # declared node outputs (e.g. change:workflow-state.yaml).
            basename = logical.segments[-1] if logical.segments else ""
            if basename in _EXCLUDED_FILES and workspace is not None and (workspace.root / rel).is_file():
                data = (workspace.root / rel).read_bytes()
                frozen[declared] = hashlib.sha256(data).hexdigest()
                continue
            raise WorkspaceError(f"declared output missing or not a file: {declared}")
        return frozen

    def load_write_set(self, write_set_id: str) -> WriteSet:
        """按内容地址读回 write-set；字节篡改在 hash 校验处 fail closed。"""
        payload = json.loads(self._read_object(write_set_id))
        if not isinstance(payload, dict) or payload.get("kind") != "write_set":
            raise WorkspaceError(f"invalid write-set manifest: {write_set_id}")
        fields = {k: v for k, v in payload.items() if k not in ("kind", "version")}
        try:
            return WriteSet.model_validate({**fields, "write_set_id": write_set_id})
        except ValueError as exc:
            raise WorkspaceError(f"invalid write-set manifest {write_set_id}: {exc}") from exc

    # ---- Update：确定性合并 + canonical 幂等物化 ----

    def merge_write_sets(self, write_sets: Iterable[WriteSet]) -> str:
        """按 structural task ID 排序合并同 wave write-sets，返回 target tree id。

        sibling 实际触碰同一逻辑路径、entry 的 before_sha256 与 base tree 不一致、
        或 write-sets 不共享同一 base，一律 fail closed。
        """
        ordered = sorted(write_sets, key=lambda write_set: write_set.task_id)
        if not ordered:
            raise WorkspaceError("no write-sets to merge")
        base_ids = {write_set.base_tree_id for write_set in ordered}
        if len(base_ids) != 1:
            raise WorkspaceError("write-sets do not share one base tree")
        base = self._load_tree(ordered[0].base_tree_id)
        entries = dict(base.entries)
        touched: dict[str, str] = {}
        for write_set in ordered:
            for entry in write_set.entries:
                previous = touched.get(entry.logical_path)
                if previous is not None:
                    raise WorkspaceError(
                        f"overlapping sibling write-sets at {entry.logical_path}: "
                        f"{previous} vs {write_set.task_id}"
                    )
                touched[entry.logical_path] = write_set.task_id
                logical = ResourcePath.parse(entry.logical_path)
                rel = _physical_for(base.roots, logical)
                current = entries.get(rel)
                current_sha = current.sha256 if current else None
                if entry.before_sha256 != current_sha:
                    raise WorkspaceError(
                        f"write-set entry {entry.logical_path} before_sha256 disagrees with base tree"
                    )
                if entry.operation == "delete":
                    del entries[rel]
                else:
                    if entry.after_sha256 is None:
                        raise WorkspaceError(f"write-set entry missing after_sha256: {entry.logical_path}")
                    entries[rel] = _Entry(kind="file", sha256=entry.after_sha256, executable=entry.executable)
        raw = _canonical_json(_tree_payload(base.roots, entries))
        target_tree_id = hashlib.sha256(raw).hexdigest()
        self._write_object(target_tree_id, raw)
        return target_tree_id

    def apply_tree(self, project_root: Path, target_tree_id: str, *, base_tree_id: str) -> None:
        """把 canonical root 从 base tree 幂等推进到 target tree。

        先整体验证：任何落在 ``{base, target}`` 之外的状态都是 canonical 漂移，
        fail closed 且不触碰磁盘。之后写 entry 用 temp-file + ``os.replace``、
        delete 最后执行；partial apply 后重放同一 target 必收敛。
        """
        project_root = project_root.resolve()
        base = self._load_tree(base_tree_id)
        target = self._load_tree(target_tree_id)
        current = _walk(project_root, keep_change_dir=self._change_dir)
        writes: list[tuple[str, _Entry]] = []
        deletes: list[str] = []
        for rel in sorted(set(base.entries) | set(target.entries)):
            if _is_excluded_rel(rel):
                continue
            before = base.entries.get(rel)
            wanted = target.entries.get(rel)
            actual = current.get(rel)
            if before == wanted:
                if actual != before:
                    raise WorkspaceError(f"canonical workspace drift at {rel}")
                continue
            if actual == wanted:
                continue  # 已物化（重放/幂等）
            if actual != before:
                raise WorkspaceError(f"canonical workspace drift at {rel}")
            if wanted is None:
                deletes.append(rel)
            else:
                if wanted.kind != "file":
                    raise WorkspaceError(f"cannot materialize non-file entry: {rel}")
                writes.append((rel, wanted))
        for rel in sorted(set(current) - set(base.entries) - set(target.entries)):
            if _is_excluded_rel(rel):
                continue
            raise WorkspaceError(f"canonical workspace drift: untracked path {rel}")

        for rel, entry in writes:
            _install_file(project_root / rel, self._read_object(entry.sha256), entry.executable)
        for rel in deletes:
            victim = project_root / rel
            victim.unlink(missing_ok=True)
            _prune_empty_parents(victim, project_root)


