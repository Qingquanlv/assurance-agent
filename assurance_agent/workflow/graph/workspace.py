# TreeStore：内容寻址对象库 + tree capture/materialize + write-set freeze/merge


class TreeStore:
    """change dir 下的内容寻址对象库；coordinator 独占写入。"""

    def __init__(self, change_dir: Path) -> None:
        self._change_dir = change_dir
        self._objects = change_dir / _OBJECTS_RELPATH

    # ---- 对象库原语 ----

    def _object_path(self, digest: str) -> Path:
        _assert_digest(digest)
        return self._objects / digest[:2] / digest

    def _write_object(self, digest: str, data: bytes) -> None:
        path = self._object_path(digest)
        path.parent.mkdir(parents=True, exist_ok=True)
        try:
            with open(path, "xb") as handle:
                handle.write(data)
                handle.flush()
                os.fsync(handle.fileno())
        except FileExistsError:
            # 已存在的对象必须先验证 hash 再复用：篡改/冲突不允许静默通过。
            self._read_object(digest)

    def _read_object(self, digest: str) -> bytes:
        path = self._object_path(digest)
        try:
            data = path.read_bytes()
        except OSError as exc:
            raise WorkspaceError(f"object missing from store: {digest}") from exc
        if hashlib.sha256(data).hexdigest() != digest:
            raise WorkspaceError(f"object store bytes tampered: {digest}")
        return data

    def read_object(self, digest: str) -> bytes:
        """Read content-addressed blob bytes (public wrapper)."""
        return self._read_object(digest)

    # ---- tree capture / materialize ----

    def _roots(self, project_root: Path, repo_root: Path | None) -> dict[str, str]:
        def prefix(path: Path) -> str:
            resolved = path.resolve()
            if resolved == project_root:
                return "."
            try:
                return resolved.relative_to(project_root).as_posix()
            except ValueError as exc:
                raise WorkspaceError(f"logical root escapes project root: {path}") from exc

        return {
            "change": prefix(self._change_dir),
            "project": ".",
            "repo": prefix(repo_root) if repo_root is not None else ".",
        }

    def capture(self, project_root: Path, *, repo_root: Path | None = None) -> str:
        """把 project root 固化成内容寻址 tree manifest，返回 tree id（确定性）。"""
        project_root = project_root.resolve()
        if not project_root.is_dir():
            raise WorkspaceError(f"project root is not a directory: {project_root}")
        roots = self._roots(project_root, repo_root)
        entries = _walk(project_root, keep_change_dir=self._change_dir)
        for rel, entry in entries.items():
            if entry.kind == "file":
                data = (project_root / rel).read_bytes()
                if hashlib.sha256(data).hexdigest() != entry.sha256:
                    raise WorkspaceError(f"path changed during capture: {rel}")
            else:
                data = os.readlink(project_root / rel).encode("utf-8")
            self._write_object(entry.sha256, data)
        raw = _canonical_json(_tree_payload(roots, entries))
        tree_id = hashlib.sha256(raw).hexdigest()
        self._write_object(tree_id, raw)
        return tree_id

    def _load_tree(self, tree_id: str) -> _TreeManifest:
        return _parse_tree(self._read_object(tree_id))

    def _read_tree_bytes(
        self,
        manifest: _TreeManifest,
        rel: str,
    ) -> bytes:
        current = rel
        visited_states: set[str] = set()
        hops = 0
        while True:
            if current in visited_states:
                raise WorkspaceError(f"tree symlink cycle while resolving: {current}")
            visited_states.add(current)
            parts = PurePosixPath(current).parts
            followed = False
            for index in range(1, len(parts) + 1):
                prefix = PurePosixPath(*parts[:index]).as_posix()
                entry = manifest.entries.get(prefix)
                if entry is None:
                    continue
                data = self._read_object(entry.sha256)
                if entry.kind == "file":
                    if index != len(parts):
                        raise NotADirectoryError(current)
                    return data
                if hops >= _MAX_TREE_SYMLINK_HOPS:
                    raise WorkspaceError(f"too many symlink hops while resolving tree path: {rel}")
                try:
                    target = data.decode("utf-8")
                except UnicodeDecodeError as exc:
                    raise WorkspaceError(f"tree symlink target is not UTF-8: {prefix}") from exc
                hops += 1
                resolved = _resolve_tree_symlink(prefix, target)
                current = PurePosixPath(resolved, *parts[index:]).as_posix()
                followed = True
                break
            if followed:
                continue
            directory_prefix = f"{current}/"
            if current == "." or any(path.startswith(directory_prefix) for path in manifest.entries):
                raise IsADirectoryError(current)
            raise FileNotFoundError(current)

    def read_bytes(self, tree_id: str, logical_path: str) -> bytes:
        """Read hash-verified file bytes from a committed tree, following safe symlinks."""
        logical = ResourcePath.parse(logical_path)
        manifest = self._load_tree(tree_id)
        rel = _physical_for(manifest.roots, logical)
        try:
            return self._read_tree_bytes(manifest, rel)
        except FileNotFoundError as exc:
            raise FileNotFoundError(logical_path) from exc

    def read_json(self, tree_id: str, logical_path: str) -> ResolvedArtifact:
        """Read a JSON artifact from a committed tree by logical path (change:/project:/repo:)."""
        data = self.read_bytes(tree_id, logical_path)
        try:
            value = json.loads(data.decode("utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError) as exc:
            raise ValueError(f"artifact is not valid JSON: {logical_path}") from exc
        return ResolvedArtifact(
            value=value,
            reads_sha256={logical_path: hashlib.sha256(data).hexdigest()},
        )

    def filter_tree(
        self,
        tree_id: str,
        claims: ResourceClaims,
        *,
        declared_reads_only: bool = False,
        skill_name: str | None = None,
    ) -> str:
        """Return the task's materializable read view without changing its merge base.

        When task claims name concrete ``project:qa/retro/<id>/...`` paths,
        other ``qa/retro/<sibling>/`` entries are dropped from the materialized
        workspace. With ``declared_reads_only``, every entry outside declared
        contract/node reads is removed as well; ``skills/<skill_name>/**`` remains
        visible so the selected agent can load its own bundle. The freeze/merge
        ``base_tree_id`` stays the full overlay tree — callers must not rebind it
        to this filtered id.
        """
        manifest = self._load_tree(tree_id)
        claimed_retro_ids = _claimed_retro_run_ids(claims)
        if not claimed_retro_ids and not declared_reads_only:
            return tree_id
        entries = {}
        for rel, entry in manifest.entries.items():
            if _is_omitted_retro_sibling(manifest.roots, rel, claimed_retro_ids):
                continue
            if declared_reads_only and not _entry_visible_to_declared_skill(
                manifest.roots,
                rel,
                claims,
                skill_name,
            ):
                continue
            entries[rel] = entry
        if entries == manifest.entries:
            return tree_id
        raw = _canonical_json(_tree_payload(manifest.roots, entries))
        filtered_id = hashlib.sha256(raw).hexdigest()
        self._write_object(filtered_id, raw)
        return filtered_id

    def materialize(self, tree_id: str, dest: Path) -> None:
        """把 tree 物化到空目录 ``dest``，并写入 ``.graph-runtime/tree.json`` 元数据。"""
        manifest = self._load_tree(tree_id)
        dest = dest.resolve()
        dest.mkdir(parents=True, exist_ok=True)
        for prefix in manifest.roots.values():
            (dest / prefix).mkdir(parents=True, exist_ok=True)
        for rel, entry in sorted(manifest.entries.items()):
            target = (dest / rel).resolve()
            if not _is_within(target, dest):
                raise WorkspaceError(f"tree entry escapes materialization root: {rel}")
            data = self._read_object(entry.sha256)
            if entry.kind == "symlink":
                link_target = data.decode("utf-8")
                if not _is_within((target.parent / link_target).resolve(), dest):
                    raise WorkspaceError(f"tree symlink escapes materialization root: {rel}")
                target.parent.mkdir(parents=True, exist_ok=True)
                os.symlink(link_target, target)
            else:
                _install_file(target, data, entry.executable)
        manifest_path = dest / _TREE_MANIFEST_RELPATH
        manifest_path.parent.mkdir(parents=True, exist_ok=True)
        manifest_path.write_bytes(manifest.raw)

