# 文件系统遍历（capture/freeze/apply 共用同一套排除与 symlink 规则）


def _is_excluded_name(name: str) -> bool:
    if name in _EXCLUDED_FILES:
        return True
    # pytest-cov may write host-pid variants like ``.coverage.hostname.1234``.
    return name.startswith(".coverage.")


def _is_top_level_issue_ledger(rel: str | PurePosixPath) -> bool:
    parts = PurePosixPath(rel).parts
    return (
        len(parts) == 5
        and parts[0] == "qa"
        and parts[1] in {"changes", "archive"}
        and parts[3:] == ("issues", "events.jsonl")
    )


def _is_excluded_rel(rel: str) -> bool:
    """True when any path segment is an excluded dir or the basename is excluded."""
    parts = [part for part in rel.split("/") if part and part != "."]
    if not parts:
        return False
    # Change Issue ledgers are canonical domain data, not the change-dir graph
    # coordinator ledger.  They must participate in capture/freeze/apply so a
    # later execution batch can replay all Observations and Occurrences.
    if _is_top_level_issue_ledger(rel):
        return False
    if _is_excluded_name(parts[-1]):
        return True
    return any(part in _EXCLUDED_DIRS for part in parts[:-1] or parts)


def _is_synchronized_ledger_rel(
    roots: Mapping[str, str],
    rel: str,
    synchronized: Sequence[ResourcePath],
) -> bool:
    """Project ledger JSONL under synchronized prefixes must still publish.

    Basename ``events.jsonl`` is globally capture-excluded (change-dir coordinator),
    but ``qa/issues/events.jsonl`` / ``qa/improvements/events.jsonl`` are canonical
    ledgers and must ride synchronized write-sets.
    """
    if not synchronized:
        return False
    parts = [part for part in rel.split("/") if part and part != "."]
    if not parts or parts[-1] != "events.jsonl":
        return False
    try:
        logical = ResourcePath.parse(_canonical_logical(roots, rel))
    except WorkspaceError:
        return False
    return logical.root == "project" and any(path_covers(prefix, logical) for prefix in synchronized)


def _walk(root: Path, *, keep_change_dir: Path | None = None) -> dict[str, _Entry]:
    root = root.resolve()
    keep_prefix: str | None = None
    if keep_change_dir is not None:
        keep = keep_change_dir.resolve()
        if _is_within(keep, root):
            keep_prefix = keep.relative_to(root).as_posix()
    entries: dict[str, _Entry] = {}

    def visit(directory: Path, prefix: str) -> None:
        with os.scandir(directory) as children:
            for child in children:
                rel = f"{prefix}{child.name}"
                if _is_excluded_rel(rel):
                    continue
                # Sibling qa/changes/<other-id>/ must not enter this change's tree —
                # the loop keeps multiple in-flight change dirs under one SUT.
                if (
                    keep_prefix is not None
                    and rel.startswith("qa/changes/")
                    and rel != keep_prefix
                    and not rel.startswith(f"{keep_prefix}/")
                ):
                    continue
                # Excluded roots are skipped whatever their kind, matching
                # ``_is_excluded_rel``: tooling often leaves ``.venv`` as a symlink to a
                # shared interpreter, which must not fail the walk for pointing outside.
                if child.name in _EXCLUDED_DIRS:
                    continue
                if child.is_dir(follow_symlinks=False):
                    visit(Path(child.path), f"{rel}/")
                    continue
                if child.is_symlink():
                    target = os.readlink(child.path)
                    resolved = (Path(child.path).parent / target).resolve()
                    if not _is_within(resolved, root):
                        raise WorkspaceError(f"symlink resolves outside its logical root: {rel}")
                    data = target.encode("utf-8")
                    entries[rel] = _Entry(kind="symlink", sha256=hashlib.sha256(data).hexdigest())
                    continue
                if child.is_file(follow_symlinks=False):
                    data = Path(child.path).read_bytes()
                    executable = bool(child.stat(follow_symlinks=False).st_mode & 0o100)
                    entries[rel] = _Entry(
                        kind="file", sha256=hashlib.sha256(data).hexdigest(), executable=executable
                    )
                    continue
                raise WorkspaceError(f"unsupported filesystem entry: {rel}")

    visit(root, "")
    return entries


def _install_file(path: Path, data: bytes, executable: bool) -> None:
    """temp-file + os.replace 落盘并固定 mode；apply 阶段的最小写入单元。"""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.parent / f"{path.name}.tmp.{os.getpid()}"
    try:
        tmp.write_bytes(data)
        # The replacement must publish content and mode as one filesystem state.
        # Otherwise a crash after replace leaves content-at-target with mode-at-base,
        # which is neither side of the replay comparison.
        os.chmod(tmp, 0o755 if executable else 0o644)
        os.replace(tmp, path)
    finally:
        tmp.unlink(missing_ok=True)


def _same_file_content(left: _Entry | None, right: _Entry | None) -> bool:
    """Whether two entries differ, if at all, only in executable mode."""
    return (
        left is not None
        and right is not None
        and left.kind == "file"
        and right.kind == "file"
        and left.sha256 == right.sha256
    )


def _path_matches_entry(path: Path, entry: _Entry) -> bool:
    """Whether on-disk bytes match a tree/write-set file entry."""
    if entry.kind != "file" or not path.is_file():
        return False
    return hashlib.sha256(path.read_bytes()).hexdigest() == entry.sha256


def _prune_empty_parents(path: Path, stop: Path) -> None:
    parent = path.parent
    while parent != stop and _is_within(parent, stop):
        try:
            parent.rmdir()
        except OSError:
            return
        parent = parent.parent


def _validated_synchronized_paths(
    paths: Sequence[ResourcePath | str],
) -> tuple[ResourcePath, ...]:
    validated: dict[str, ResourcePath] = {}
    for value in paths:
        path = ResourcePath.parse(value) if isinstance(value, str) else value
        if path.root != "project":
            raise WorkspaceError(f"synchronized path must use the project root: {path.root}:{path.pattern}")
        wildcard_segments = [segment for segment in path.segments if "*" in segment]
        if wildcard_segments and not (wildcard_segments == ["**"] and path.segments[-1] == "**"):
            raise WorkspaceError(
                f"synchronized path must be a concrete file or directory prefix: {path.pattern}"
            )
        validated[path.pattern] = path
    return tuple(validated[key] for key in sorted(validated))


def _matches_synchronized_path(
    roots: Mapping[str, str],
    rel: str,
    synchronized: Sequence[ResourcePath],
) -> bool:
    prefix = roots.get("project")
    if prefix is None:
        raise WorkspaceError("tree manifest missing project logical root")
    prefix = _assert_safe_prefix(prefix)
    if prefix == ".":
        logical_rel = rel
    elif rel.startswith(f"{prefix}/"):
        logical_rel = rel[len(prefix) + 1 :]
    else:
        return False
    logical = ResourcePath.parse(f"project:{logical_rel}")
    return any(path_covers(path, logical) for path in synchronized)


def _capture_synchronized_entries(
    project_root: Path,
    roots: Mapping[str, str],
    synchronized: Sequence[ResourcePath],
    *,
    active_change_dir: Path | None = None,
) -> dict[str, tuple[_Entry, bytes]]:
    captured: dict[str, tuple[_Entry, bytes]] = {}
    for path in synchronized:
        rel_pattern = _physical_for(roots, path)
        if path.segments[-1] == "**":
            directory_rel = rel_pattern.removesuffix("/**")
            directory = project_root / directory_rel
            if not _is_within(directory.parent.resolve(), project_root):
                raise WorkspaceError(f"synchronized directory escapes project root: {path.pattern}")
            if directory.is_symlink():
                raise WorkspaceError(f"synchronized directory cannot be a symlink: {path.pattern}")
            if not directory.exists():
                continue
            if not directory.is_dir():
                raise WorkspaceError(f"synchronized prefix is not a directory: {path.pattern}")
            for child_rel, entry in _walk(directory).items():
                full_rel = f"{directory_rel}/{child_rel}"
                source = project_root / full_rel
                if entry.kind == "file":
                    data = source.read_bytes()
                else:
                    data = os.readlink(source).encode("utf-8")
                if hashlib.sha256(data).hexdigest() != entry.sha256:
                    raise WorkspaceError(f"synchronized path changed during capture: {full_rel}")
                captured[full_rel] = (entry, data)
            # Ledger JSONL is basename-excluded from _walk; include it for live overlay.
            events_rel = f"{directory_rel}/events.jsonl" if directory_rel else "events.jsonl"
            events_captured = _entry_and_bytes_at(project_root, events_rel)
            if events_captured is not None:
                captured[events_rel] = events_captured
            # The normal tree walk excludes every events.jsonl basename because
            # the active Change coordinator mutates its ledger during execution.
            # A synchronized Retro snapshot still needs immutable sibling Change
            # workflow and Issue ledgers, so capture those two known locations
            # explicitly while keeping the active coordinator ledger excluded.
            if directory_rel in {"qa/changes", "qa/archive"}:
                active = active_change_dir.resolve() if active_change_dir is not None else None
                for change_dir in sorted(path for path in directory.iterdir() if path.is_dir()):
                    for suffix in (Path("events.jsonl"), Path("issues/events.jsonl")):
                        ledger = change_dir / suffix
                        if active is not None and ledger.resolve() == (active / suffix).resolve():
                            continue
                        ledger_rel = ledger.relative_to(project_root).as_posix()
                        ledger_captured = _entry_and_bytes_at(project_root, ledger_rel)
                        if ledger_captured is not None:
                            captured[ledger_rel] = ledger_captured
            continue
        file_captured = _entry_and_bytes_at(project_root, rel_pattern)
        if file_captured is not None:
            captured[rel_pattern] = file_captured
    return captured


def _synchronized_ledger_entries(
    workspace_root: Path,
    roots: Mapping[str, str],
    synchronized: Sequence[ResourcePath],
) -> dict[str, _Entry]:
    """Collect workspace ``events.jsonl`` files under synchronized project prefixes."""
    found: dict[str, _Entry] = {}
    for path in synchronized:
        if path.root != "project" or path.segments[-1] != "**":
            continue
        directory_rel = path.pattern.removesuffix("/**")
        events_rel = f"{directory_rel}/events.jsonl" if directory_rel else "events.jsonl"
        physical = _physical_for(roots, ResourcePath.parse(f"project:{events_rel}"))
        entry = _entry_at(workspace_root, physical)
        if entry is not None:
            found[physical] = entry
        if directory_rel in {"qa/changes", "qa/archive"}:
            directory = workspace_root / _physical_for(
                roots,
                ResourcePath.parse(f"project:{directory_rel}"),
            )
            if not directory.is_dir():
                continue
            for change_dir in sorted(item for item in directory.iterdir() if item.is_dir()):
                for suffix in (Path("events.jsonl"), Path("issues/events.jsonl")):
                    ledger = change_dir / suffix
                    ledger_rel = ledger.relative_to(workspace_root).as_posix()
                    ledger_entry = _entry_at(workspace_root, ledger_rel)
                    if ledger_entry is not None:
                        found[ledger_rel] = ledger_entry
    return found


def _entry_and_bytes_at(project_root: Path, rel: str) -> tuple[_Entry, bytes] | None:
    root = project_root.resolve()
    target = root / rel
    if not _is_within(target.parent.resolve(), root):
        raise WorkspaceError(f"targeted path escapes project root: {rel}")
    if target.is_symlink():
        link_target = os.readlink(target)
        if not _is_within((target.parent / link_target).resolve(), project_root):
            raise WorkspaceError(f"targeted symlink escapes project root: {rel}")
        data = link_target.encode("utf-8")
        return _Entry(kind="symlink", sha256=hashlib.sha256(data).hexdigest()), data
    if not target.exists():
        return None
    if not target.is_file():
        raise WorkspaceError(f"targeted write-set path is not a file: {rel}")
    data = target.read_bytes()
    executable = bool(target.stat(follow_symlinks=False).st_mode & 0o100)
    return (
        _Entry(kind="file", sha256=hashlib.sha256(data).hexdigest(), executable=executable),
        data,
    )


def _entry_at(project_root: Path, rel: str) -> _Entry | None:
    captured = _entry_and_bytes_at(project_root, rel)
    return captured[0] if captured is not None else None


