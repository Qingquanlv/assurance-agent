class WorkspaceError(AaError):
    """workspace/tree/write-set 完整性或授权失败；一律 fail closed。"""


# ---------------------------------------------------------------------------
# 内部模型与规范 JSON


@dataclass(frozen=True)
class _Entry:
    kind: Literal["file", "symlink"]
    sha256: str
    executable: bool = False


@dataclass(frozen=True)
class _TreeManifest:
    roots: dict[str, str]
    entries: dict[str, _Entry]
    raw: bytes


def _canonical_json(payload: Mapping[str, object]) -> bytes:
    return json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")


def _tree_payload(roots: Mapping[str, str], entries: Mapping[str, _Entry]) -> dict[str, object]:
    return {
        "entries": [
            {"executable": entry.executable, "kind": entry.kind, "path": path, "sha256": entry.sha256}
            for path, entry in sorted(entries.items())
        ],
        "kind": "tree",
        "roots": dict(sorted(roots.items())),
        "version": 1,
    }


def _assert_safe_prefix(prefix: object) -> str:
    if not isinstance(prefix, str) or not prefix:
        raise WorkspaceError(f"invalid tree root prefix: {prefix!r}")
    if prefix == ".":
        return prefix
    parts = prefix.split("/")
    if prefix.startswith("/") or "\\" in prefix or any(part in ("", ".", "..") for part in parts):
        raise WorkspaceError(f"unsafe tree root prefix: {prefix!r}")
    return prefix


def _parse_tree(raw: bytes) -> _TreeManifest:
    try:
        payload = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise WorkspaceError(f"invalid tree manifest: {exc}") from exc
    if not isinstance(payload, dict) or payload.get("kind") != "tree":
        raise WorkspaceError("invalid tree manifest: missing kind")
    raw_roots = payload.get("roots")
    if not isinstance(raw_roots, dict):
        raise WorkspaceError("invalid tree manifest: roots must be a mapping")
    roots = {str(name): _assert_safe_prefix(prefix) for name, prefix in raw_roots.items()}
    raw_entries = payload.get("entries")
    if not isinstance(raw_entries, list):
        raise WorkspaceError("invalid tree manifest: entries must be a list")
    entries: dict[str, _Entry] = {}
    for item in raw_entries:
        if not isinstance(item, dict):
            raise WorkspaceError("invalid tree manifest: entry must be a mapping")
        path = item.get("path")
        kind = item.get("kind")
        sha256 = item.get("sha256")
        if not isinstance(path, str) or kind not in ("file", "symlink") or not isinstance(sha256, str):
            raise WorkspaceError(f"invalid tree manifest entry: {item!r}")
        _assert_digest(sha256)
        entries[path] = _Entry(kind=kind, sha256=sha256, executable=bool(item.get("executable", False)))
    return _TreeManifest(roots=roots, entries=entries, raw=raw)


def _assert_digest(digest: str) -> None:
    if len(digest) != 64 or any(ch not in _HEX for ch in digest):
        raise WorkspaceError(f"invalid object digest: {digest!r}")


def _is_within(path: Path, root: Path) -> bool:
    try:
        path.relative_to(root)
    except ValueError:
        return False
    return True


# ---------------------------------------------------------------------------
# 文件系统遍历（capture/freeze/apply 共用同一套排除与 symlink 规则）


def _is_excluded_name(name: str) -> bool:
    if name in _EXCLUDED_FILES:
        return True
    # pytest-cov may write host-pid variants like ``.coverage.hostname.1234``.
    return name.startswith(".coverage.")


def _is_excluded_rel(rel: str) -> bool:
    """True when any path segment is an excluded dir or the basename is excluded."""
    parts = [part for part in rel.split("/") if part and part != "."]
    if not parts:
        return False
    if _is_excluded_name(parts[-1]):
        return True
    return any(part in _EXCLUDED_DIRS for part in parts[:-1] or parts)


def _walk(root: Path, *, keep_change_dir: Path | None = None) -> dict[str, _Entry]:
    root = root.resolve()
    keep_prefix: str | None = None
    if keep_change_dir is not None:
        keep = keep_change_dir.resolve()
        if _is_within(keep, root):
            keep_prefix = keep.relative_to(root).as_posix()
    entries: dict[str, _Entry] = {}

    def visit(directory: Path, prefix: str) -> None:
        with os.scandir(directory) as children:
            for child in children:
                rel = f"{prefix}{child.name}"
                if _is_excluded_name(child.name):
                    continue
                # Sibling qa/changes/<other-id>/ must not enter this change's tree —
                # the loop keeps multiple in-flight change dirs under one SUT.
                if (
                    keep_prefix is not None
                    and rel.startswith("qa/changes/")
                    and rel != keep_prefix
                    and not rel.startswith(f"{keep_prefix}/")
                ):
                    continue
                if child.is_dir(follow_symlinks=False):
                    if child.name not in _EXCLUDED_DIRS:
                        visit(Path(child.path), f"{rel}/")
                    continue
                if child.is_symlink():
                    target = os.readlink(child.path)
                    resolved = (Path(child.path).parent / target).resolve()
                    if not _is_within(resolved, root):
                        raise WorkspaceError(f"symlink resolves outside its logical root: {rel}")
                    data = target.encode("utf-8")
                    entries[rel] = _Entry(kind="symlink", sha256=hashlib.sha256(data).hexdigest())
                    continue
                if child.is_file(follow_symlinks=False):
                    data = Path(child.path).read_bytes()
                    executable = bool(child.stat(follow_symlinks=False).st_mode & 0o100)
                    entries[rel] = _Entry(
                        kind="file", sha256=hashlib.sha256(data).hexdigest(), executable=executable
                    )
                    continue
                raise WorkspaceError(f"unsupported filesystem entry: {rel}")

    visit(root, "")
    return entries


def _install_file(path: Path, data: bytes, executable: bool) -> None:
    """temp-file + os.replace 落盘并固定 mode；apply 阶段的最小写入单元。"""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.parent / f"{path.name}.tmp.{os.getpid()}"
    tmp.write_bytes(data)
    os.replace(tmp, path)
    os.chmod(path, 0o755 if executable else 0o644)


def _prune_empty_parents(path: Path, stop: Path) -> None:
    parent = path.parent
    while parent != stop and _is_within(parent, stop):
        try:
            parent.rmdir()
        except OSError:
            return
        parent = parent.parent


